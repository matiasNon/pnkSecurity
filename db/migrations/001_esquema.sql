-- 001_esquema.sql
-- Esquema PostgreSQL de la carta digital (migracion desde el volcado MySQL pnk_security.sql).
-- Cambios respecto al original (ver docs/MIGRACION.md):
--   * restautantes (typo)  -> restaurantes
--   * Id -> id; bit(1) -> boolean; datetime -> timestamptz; AUTO_INCREMENT -> IDENTITY
--   * se agregan claves foraneas, UNIQUE de email (citext), indices en las FK y CHECK de rangos
--   * borrado logico con eliminado_en (se conserva la semantica "eliminado IS NULL")
--   * usuarios con rol y restaurante_id (el admin solo gestiona su restaurante)
--   * contrasenas con hash (formato scrypt$N$r$p$sal$hash), nunca texto plano

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE direcciones (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calle         varchar(100) NOT NULL,
  numero        varchar(15)  NOT NULL,
  comuna        varchar(100) NOT NULL,
  region        varchar(100),
  creado_en     timestamptz  NOT NULL DEFAULT now(),
  actualizado_en timestamptz,
  eliminado_en  timestamptz
);

CREATE TABLE restaurantes (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rut           varchar(11)  NOT NULL,
  nombre        varchar(200) NOT NULL,
  fono          varchar(45)  NOT NULL,
  mapa          varchar(200),
  foto          varchar(200),
  email         varchar(100),
  direccion_id  integer      NOT NULL REFERENCES direcciones(id),
  creado_en     timestamptz  NOT NULL DEFAULT now(),
  actualizado_en timestamptz,
  eliminado_en  timestamptz
);
CREATE INDEX idx_restaurantes_direccion ON restaurantes(direccion_id);

CREATE TABLE cartas (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(45),
  orden         integer,
  visible       boolean      NOT NULL DEFAULT true,
  foto          varchar(200),
  restaurante_id integer     NOT NULL REFERENCES restaurantes(id),
  creado_en     timestamptz  NOT NULL DEFAULT now(),
  actualizado_en timestamptz,
  eliminado_en  timestamptz
);
CREATE INDEX idx_cartas_restaurante ON cartas(restaurante_id);

CREATE TABLE categorias (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(100) NOT NULL,
  visible       boolean      NOT NULL DEFAULT false,
  foto          varchar(200),
  orden         integer,
  carta_id      integer      NOT NULL REFERENCES cartas(id),
  creado_en     timestamptz  NOT NULL DEFAULT now(),
  actualizado_en timestamptz,
  eliminado_en  timestamptz
);
CREATE INDEX idx_categorias_carta ON categorias(carta_id);

CREATE TABLE items (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(100) NOT NULL,
  descripcion   varchar(300),
  tiempo        varchar(100),
  observaciones varchar(300),
  precio        integer      CHECK (precio IS NULL OR precio >= 0),
  visible       boolean      NOT NULL DEFAULT false,
  destacado     boolean      NOT NULL DEFAULT false,
  puntuacion    integer      NOT NULL DEFAULT 0 CHECK (puntuacion BETWEEN 0 AND 5),
  foto          varchar(200),
  orden         integer,
  categoria_id  integer      NOT NULL REFERENCES categorias(id),
  creado_en     timestamptz  NOT NULL DEFAULT now(),
  actualizado_en timestamptz,
  eliminado_en  timestamptz
);
CREATE INDEX idx_items_categoria ON items(categoria_id);

CREATE TABLE usuarios (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(255) NOT NULL,
  email         citext       NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  rol           varchar(10)  NOT NULL DEFAULT 'cliente' CHECK (rol IN ('admin', 'cliente')),
  -- Un admin gestiona solo este restaurante (evita IDOR entre restaurantes). NULL para clientes.
  restaurante_id integer     REFERENCES restaurantes(id),
  habilitado    boolean      NOT NULL DEFAULT true,
  creado_en     timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_admin_con_restaurante CHECK (rol <> 'admin' OR restaurante_id IS NOT NULL)
);

CREATE TABLE comentarios (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario       varchar(255) NOT NULL,
  comentario    text         NOT NULL CHECK (char_length(comentario) BETWEEN 1 AND 1000),
  restaurante_id integer     NOT NULL REFERENCES restaurantes(id),
  usuario_id    integer      REFERENCES usuarios(id),
  creado_en     timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_comentarios_restaurante ON comentarios(restaurante_id, id DESC);
